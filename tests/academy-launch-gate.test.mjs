import assert from 'node:assert/strict';
import fs from 'node:fs';
import {evaluateLaunchEvidence} from '../scripts/academy-launch-gate.mjs';
const manifest=JSON.parse(fs.readFileSync('docs/IAgile-LAUNCH-EVIDENCE.json','utf8'));
const r=evaluateLaunchEvidence(manifest);
assert.equal(r.ready,false,'No IAgile payment or premium course should be opened yet');
assert.equal(r.total,15);
assert.equal(r.verified,2);
assert(r.blocked.some(x=>x.id==='seller'));
assert(r.blocked.some(x=>x.id==='signed_checkout'));
const cloned=structuredClone(manifest);
cloned.gates=cloned.gates.map(x=>({...x,status:'verified',evidence:'Synthetic verified result with independent written evidence link (test only)'}));
assert.equal(evaluateLaunchEvidence(cloned).ready,true);
cloned.gates.pop();
assert.throws(()=>evaluateLaunchEvidence(cloned),/Missing launch gate/);
cloned.gates=manifest.gates.map(x=>({...x}));
cloned.gates[0].status='unknown';
assert.throws(()=>evaluateLaunchEvidence(cloned),/Invalid gate/);
console.log('PASS sales readiness gates explicitly blocked; checker refuses missing and invalid evidence');
