import assert from 'node:assert/strict';
import {sample3DEnvironment,safeChecklist} from '../academy-app/diagnostic-3d-policy.mjs';
const html=sample3DEnvironment({width:320,height:700,motion:true,webgl1:false,webgl2:false});
assert.equal(html.backend,'html');
assert.equal(html.verdict,'fallback');
assert.equal(html.smallViewport,true);
assert.equal(html.motionReduced,true);
assert.equal(html.tested.frames,false);
assert(safeChecklist(html).some(x=>x.includes('sans WebGL')));
assert(safeChecklist(html).some(x=>x.includes('mouvement réduit')));
const gpu=sample3DEnvironment({width:1280,height:720,motion:false,webgl1:true,webgl2:true});
assert.equal(gpu.backend,'webgl2');
assert.equal(gpu.verdict,'device-check-required');
assert.equal(gpu.tested.context,true);
assert.equal(gpu.tested.device,false);
assert(safeChecklist(gpu).some(x=>x.includes('ne prouve pas les FPS')));
assert.equal(sample3DEnvironment({width:NaN,height:0}).aspect,null);
assert.equal(sample3DEnvironment({width:375,height:812}).smallViewport,true);
console.log('PASS 3D diagnostic: HTML fallback, reduced motion, mobile, real GPU context vs untested FPS');
