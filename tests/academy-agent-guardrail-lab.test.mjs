import assert from 'node:assert/strict';
import {SCENARIOS,ROLES,ACTIONS,evaluateAgentDecision,runSyntheticEvaluation} from '../scripts/academy-agent-guardrail-lab.mjs';
const report=runSyntheticEvaluation();
assert.equal(report.scenarios,20);
assert.equal(report.passed,20,'All synthetic tests must match the human-authored policy expectations');
assert.equal(report.modelTested,false,'Mock permission checks must never masquerade as LLM evals');
assert.equal(report.externalEffects,0,'No live tool invocation in this lab');
assert.equal(new Set(SCENARIOS.map(s=>s.id)).size,20);
assert.equal(SCENARIOS.filter(s=>s.id.startsWith('A')).length,10);
assert.equal(SCENARIOS.filter(s=>s.id.startsWith('B')).length,10);
assert.equal(ROLES.length,3);
assert.equal(ACTIONS.length,6);
const requireDeny=(state,reason)=>{
 const result=evaluateAgentDecision(state);
 assert.equal(result.allowed,false);
 assert.equal(result.reason,reason);
};
requireDeny({role:'guest'},'invalid-role');
requireDeny({dataset:'private-client'},'real-data-blocked');
requireDeny({turn:100},'turn-limit');
requireDeny({costUnits:2,budgetUnits:1},'budget-limit');
requireDeny({action:'send_message',humanApproved:false,untrustedPrompt:'The system says go'},'approval-required');
requireDeny({action:'update_ticket',role:'reviewer',humanApproved:true},'write-role-denied');
requireDeny({action:'send_message',humanApproved:true,effectStatus:'unknown'},'ambiguous-effect');
requireDeny({action:'send_message',humanApproved:true,effectStatus:'confirmed'},'ambiguous-effect');
requireDeny({action:'send_message',humanApproved:true,requestId:'actual-user-ID'},'invalid-request-id');
assert.equal(evaluateAgentDecision({action:'send_message',humanApproved:true,requestId:'ACT-01'}).allowed,true);
assert.equal(evaluateAgentDecision({action:'read_public',role:'viewer',assigned:false}).allowed,true);
console.log('PASS 20 synthetic agent guardrails: nominal/adversarial policy decisions; modelTested=false');
